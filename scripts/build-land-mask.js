/**
 * Bakes Natural Earth land polygons into a compact bitmask.
 *
 * The globe needs to know which of its points sit on land. Doing that at
 * runtime would mean shipping a GeoJSON and a point-in-polygon routine to every
 * visitor; doing it here means shipping a 2.7 kB string and an array lookup.
 *
 * Usage: npm run land:sync
 * Source: Natural Earth 110m physical land, public domain.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE =
  'https://raw.githubusercontent.com/martynafford/natural-earth-geojson/master/110m/physical/ne_110m_land.json';

/** Cells per 360 degrees of longitude. 2-degree cells outresolve the dot grid. */
const WIDTH = 180;
const HEIGHT = 90;

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'src/features/globe/land-mask.ts');

/** Even-odd ray casting across every ring of one polygon, so holes work. */
function contains(rings, lon, lat) {
  let inside = false;

  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];

      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
        inside = !inside;
      }
    }
  }

  return inside;
}

function polygonsOf(geometry) {
  if (geometry.type === 'Polygon') return [geometry.coordinates];
  if (geometry.type === 'MultiPolygon') return geometry.coordinates;
  return [];
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`land data: ${response.status} ${response.statusText}`);
const geojson = await response.json();

const polygons = geojson.features.flatMap((feature) => polygonsOf(feature.geometry));

// Skip polygons whose bounding box cannot contain the sample: 127 features
// times 16,200 cells is otherwise a lot of pointless arithmetic.
const boxes = polygons.map((rings) => {
  let minLon = Infinity;
  let maxLon = -Infinity;
  let minLat = Infinity;
  let maxLat = -Infinity;

  for (const [lon, lat] of rings[0]) {
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  }

  return { minLon, maxLon, minLat, maxLat };
});

const bytes = new Uint8Array(Math.ceil((WIDTH * HEIGHT) / 8));
let land = 0;

for (let y = 0; y < HEIGHT; y++) {
  // Sample cell centres: +90 to -90 as y increases, matching image order.
  const lat = 90 - ((y + 0.5) / HEIGHT) * 180;

  for (let x = 0; x < WIDTH; x++) {
    const lon = ((x + 0.5) / WIDTH) * 360 - 180;

    for (let p = 0; p < polygons.length; p++) {
      const box = boxes[p];
      if (lon < box.minLon || lon > box.maxLon || lat < box.minLat || lat > box.maxLat) continue;

      if (contains(polygons[p], lon, lat)) {
        const bit = y * WIDTH + x;
        bytes[bit >> 3] |= 0x80 >> (bit & 7);
        land++;
        break;
      }
    }
  }
}

const coverage = ((land / (WIDTH * HEIGHT)) * 100).toFixed(1);

writeFileSync(
  out,
  `/**
 * GENERATED by scripts/build-land-mask.js — do not edit by hand.
 *
 * Natural Earth 110m physical land (public domain), rasterised to a
 * ${WIDTH}x${HEIGHT} equirectangular bitmask: row 0 is the north pole, column 0 is
 * 180 degrees west. ${land} of ${WIDTH * HEIGHT} cells are land (${coverage}%).
 */

export const LAND_MASK_WIDTH = ${WIDTH};
export const LAND_MASK_HEIGHT = ${HEIGHT};

/** One bit per cell, most significant bit first, base64 encoded. */
export const LAND_MASK_BASE64 =
  '${Buffer.from(bytes).toString('base64')}';
`,
  'utf8',
);

console.log(`land mask: ${WIDTH}x${HEIGHT}, ${coverage}% land, ${bytes.length} bytes`);
